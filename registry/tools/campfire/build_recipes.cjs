#!/usr/bin/env node
// Turns recipes.csv into my-mods/campfire/npc/campfire-recipes.txt: what each
// campfire dish is cooked from.
//
//   node build_recipes.cjs [rathena-db-dir]           write the script
//   node build_recipes.cjs [rathena-db-dir] --check   fail if it is out of date
//
// recipes.csv columns: out (the dish, an item of the campfire mod),
// ingredients ("id:amount" joined with "|"), note (for people only).
// Every dish must be in my-mods/campfire/db/item_db.yml. The ingredients are
// checked against rAthena's Renewal item tables when they are there; the
// directory defaults to vendor/rathena/db/re, so pass another one when there
// is no vendor checkout. The mod ships the generated script, never this file.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..', '..');
const CSV = path.join(__dirname, 'recipes.csv');
const ITEM_DB = path.join(ROOT, 'my-mods', 'campfire', 'db', 'item_db.yml');
const DEFAULT_DB = path.join(ROOT, 'vendor', 'rathena', 'db', 're');
const OUT = path.join(ROOT, 'my-mods', 'campfire', 'npc', 'campfire-recipes.txt');

function ids(text) {
  const out = new Set();
  for (const m of text.matchAll(/^  - Id: (\d+)/gm)) out.add(+m[1]);
  return out;
}

function parse(text, dishes, stock) {
  const rows = text.split(/\r?\n/).filter((l) => l.trim() !== '');
  const head = rows.shift();
  if (head !== 'out,ingredients,note') throw new Error(`recipes.csv: unexpected header "${head}"`);
  const seen = new Set();
  return rows.map((line, i) => {
    const where = `recipes.csv line ${i + 2}`;
    const [out, ingredients] = line.split(',');
    const id = +out;
    if (!dishes.has(id)) throw new Error(`${where}: dish ${out} is not in campfire's item_db.yml`);
    if (seen.has(id)) throw new Error(`${where}: dish ${out} has two recipes`);
    seen.add(id);
    const parts = (ingredients || '').split('|');
    for (const p of parts) {
      const m = p.match(/^(\d+):(\d+)$/);
      if (!m || +m[2] < 1) throw new Error(`${where}: "${p}" is not id:amount`);
      if (stock && !stock.has(+m[1])) throw new Error(`${where}: item ${m[1]} is not in rAthena's item tables`);
    }
    return { out: id, in: parts.join('|') };
  });
}

function render(recipes) {
  const lines = recipes.map((r, i) => `\t.r_out[${i}] = ${r.out};\t.r_in$[${i}] = "${r.in}";`);
  return `// GENERATED by registry/tools/campfire/build_recipes.cjs from recipes.csv.
// Edit the CSV and rebuild; changes here are lost.
//
// Read by the campfire (Fogata#cf) with getvariableofnpc. .r_in$ is a list of
// "item id:amount" joined with "|".

-	script	campfire_recipes	-1,{
OnInit:
\t.r_n = ${recipes.length};
${lines.join('\n')}
	end;
}
`;
}

function main() {
  const args = process.argv.slice(2);
  const dbDir = args.find((a) => !a.startsWith('--')) || DEFAULT_DB;
  let stock = null;
  const tables = ['item_db_usable.yml', 'item_db_etc.yml'].map((f) => path.join(dbDir, f));
  if (tables.every((f) => fs.existsSync(f))) {
    stock = new Set();
    for (const f of tables) for (const id of ids(fs.readFileSync(f, 'utf8'))) stock.add(id);
  } else {
    console.warn(`no rAthena item tables in ${dbDir}; ingredients not checked`);
  }
  const recipes = parse(fs.readFileSync(CSV, 'utf8'), ids(fs.readFileSync(ITEM_DB, 'utf8')), stock);
  const out = render(recipes);
  if (args.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('campfire-recipes.txt is out of date; run build_recipes.cjs');
      process.exit(1);
    }
    console.log(`up to date (${recipes.length} recipes)`);
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${recipes.length} recipes)`);
}

if (require.main === module) main();
module.exports = { parse, render };
