#!/usr/bin/env node
// Turns the dungeon rows of world-atlas's atlas.csv into
// my-mods/dungeon-chest/npc/dungeon-chests.txt: one chest per dungeon map, with
// the map's Tier and that Tier's reward as the fallback the chest uses when the
// atlas is not loaded.
//
//   node build_chests.cjs           write the script
//   node build_chests.cjs --check   fail if the script on disk is out of date
//
// Adding a chest is adding a kind=dungeon row to atlas.csv (see world-atlas's
// README) and running this script. The mod ships the generated script, never
// this file.

const fs = require('fs');
const path = require('path');
const atlas = require('../world-atlas/build_atlas.cjs');

const CSV = path.join(__dirname, '..', 'world-atlas', 'atlas.csv');
const OUT = path.join(__dirname, '..', '..', '..', 'my-mods', 'dungeon-chest', 'npc', 'dungeon-chests.txt');

// The test reward of each Tier. F_DungeonChest_Item in the script is built from
// this table, so the fallback and the atlas-driven reward cannot disagree.
const REWARDS = { 1: 12041, 2: 12042, 3: 12043, 4: 12044, 5: 12045, 6: 12071 };

// Milliseconds between a chest's checks: relocate once if unopened, refill if opened.
const TICK_MS = 600000;

function chest(map, tier) {
  const item = REWARDS[tier];
  return `${map},0,0,4\tscript\tCofre T${tier}#dcp_${map}\t3075,{
\t.@opened = callfunc("F_DungeonChest_Open", strnpcinfo(3), ${tier}, ${item});
\tif (.@opened) {
\t\tstopnpctimer;
\t\tinitnpctimer;
\t}
\tclose;

OnInit:
\t.opened = 0;
\t.relocated = 0;
\tset $@dc_npc_${map}$, strnpcinfo(3);
\tcallfunc("F_DungeonChest_Move", strnpcinfo(3), "${map}");
\tinitnpctimer;
\tend;

OnTimer${TICK_MS}:
\tcallfunc("F_DungeonChest_Tick", strnpcinfo(3), "${map}");
\tinitnpctimer;
\tend;
}
`;
}

function render(rows) {
  const dungeons = rows.filter((r) => r.kind === 'dungeon')
    .sort((a, b) => (a.map < b.map ? -1 : a.map > b.map ? 1 : 0));
  const itemCases = Object.entries(REWARDS)
    .map(([tier, item]) => `\tif (.@tier == ${tier}) return ${item};`).join('\n');

  return `// GENERATED by registry/tools/dungeon-chest/build_chests.cjs from the dungeon
// rows of registry/tools/world-atlas/atlas.csv. Edit the CSV and rebuild;
// changes here are lost.
//
// ${dungeons.length} chests, one per kind=dungeon map.

function\tscript\tF_DungeonChest_Move\t{
\t.@npc$ = getarg(0);
\t.@map$ = getarg(1);
\t.@placed = 0;
\tfor (.@try = 0; .@try < 500; .@try++) {
\t\t.@x = rand(20, 280);
\t\t.@y = rand(20, 280);
\t\tif (!checkcell(.@map$, .@x, .@y, cell_chkpass))
\t\t\tcontinue;
\t\tmovenpc .@npc$, .@x, .@y;
\t\t.@placed = 1;
\t\tbreak;
\t}

\tif (!.@placed)
\t\tdebugmes "dungeon-chest: could not find a passable cell on " + .@map$ + " after 500 attempts for " + .@npc$;
\treturn .@placed;
}

// F_DungeonChest_Item(tier) -> the test reward for a Tier, 0 for a Tier without one.
function\tscript\tF_DungeonChest_Item\t{
\t.@tier = getarg(0);
${itemCases}
\treturn 0;
}

function\tscript\tF_DungeonChest_Open\t{
\t.@npc$ = getarg(0);
\t.@tier = getarg(1);
\t.@item = getarg(2);

\t// The world-atlas mod, when loaded and aware of this map, owns the Tier. The
\t// Tier and reward in the chest definition are the fallback, so the mod
\t// behaves the same without the atlas. The NPC's own name keeps its literal Tier.
\tif ($@wa_ready) {
\t\t.@map$ = strnpcinfo(4);
\t\tif (callfunc("F_Atlas_Has", .@map$)) {
\t\t\t.@atlas_tier = callfunc("F_Atlas_Tier", .@map$);
\t\t\t.@atlas_item = callfunc("F_DungeonChest_Item", .@atlas_tier);
\t\t\tif (.@atlas_item) {
\t\t\t\t.@tier = .@atlas_tier;
\t\t\t\t.@item = .@atlas_item;
\t\t\t}
\t\t}
\t}

\tmes "[Cofre de Tier " + .@tier + "]";
\tif (getvariableofnpc(.opened, .@npc$)) {
\t\tmes "El cofre ya fue abierto. No queda botín.";
\t\treturn 0;
\t}

\tmes "El cofre está cerrado. ¿Quieres abrirlo?";
\tnext;
\tif (select("Abrirlo:Dejarlo cerrado") == 2)
\t\treturn 0;

\tif (getvariableofnpc(.opened, .@npc$)) {
\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\tmes "Alguien más llegó primero y ya abrió el cofre.";
\t\treturn 0;
\t}

\t// Un disfraz (costume_pct), equipo con afijos (gear_pct) o la comida. Todo
\t// el equipo llega sin identificar (dungeon-loot.txt).
\tif ($@dc_ready && $@dc_cosn > 0 && rand(100) < $@dc_cosp[.@tier]) {
\t\t.@cos = $@dc_cos[rand(0, $@dc_cosn - 1)];
\t\tif (!checkweight(.@cos, 1)) {
\t\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\t\tmes "No tienes espacio suficiente para cargar el botín.";
\t\t\treturn 0;
\t\t}
\t\tset getvariableofnpc(.opened, .@npc$), 1;
\t\tgetitem2 .@cos, 1, 0, 0, 0, 0, 0, 0, 0;
\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\tmes "Entre telas viejas encuentras una prenda vistosa, sin identificar.";
\t\tmes "Una Lupa dirá qué es.";
\t\treturn 1;
\t}
\t.@gear = 0;
\tif ($@dc_ready && rand(100) < $@dc_gear[.@tier])
\t\t.@gear = callfunc("F_DungeonChest_PickGear", .@tier);
\tif (.@gear) {
\t\tif (!checkweight(.@gear, 1)) {
\t\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\t\tmes "Dentro hay algo pesado y no puedes cargarlo. Aligera la mochila y vuelve.";
\t\t\treturn 0;
\t\t}
\t\tset getvariableofnpc(.opened, .@npc$), 1;
\t\tcallfunc "F_DungeonChest_GiveGear", .@gear, .@tier, strnpcinfo(4);
\t\t.@kind = getiteminfo(.@gear, ITEMINFO_TYPE);
\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\tif (.@kind == IT_WEAPON)
\t\t\tmes "Encuentras un arma sin identificar.";
\t\telse if (.@kind == IT_SHADOWGEAR)
\t\t\tmes "Encuentras una pieza de equipo de sombra sin identificar.";
\t\telse
\t\t\tmes "Encuentras una pieza de armadura sin identificar.";
\t\tmes "Una Lupa dirá qué es y qué guarda.";
\t\treturn 1;
\t}

\tif (!checkweight(.@item, 1)) {
\t\tmes "[Cofre de Tier " + .@tier + "]";
\t\tmes "No tienes espacio suficiente para cargar el botín.";
\t\treturn 0;
\t}

\tset getvariableofnpc(.opened, .@npc$), 1;
\tgetitem .@item, 1;
\tmes "[Cofre de Tier " + .@tier + "]";
\tmes "Encuentras " + getitemname(.@item) + ".";
\treturn 1;
}

function\tscript\tF_DungeonChest_Tick\t{
\t.@npc$ = getarg(0);
\t.@map$ = getarg(1);

\tif (getvariableofnpc(.opened, .@npc$)) {
\t\tset getvariableofnpc(.opened, .@npc$), 0;
\t\tset getvariableofnpc(.relocated, .@npc$), 0;
\t\tcallfunc("F_DungeonChest_Move", .@npc$, .@map$);
\t} else if (!getvariableofnpc(.relocated, .@npc$)) {
\t\tcallfunc("F_DungeonChest_Move", .@npc$, .@map$);
\t\tset getvariableofnpc(.relocated, .@npc$), 1;
\t}
\treturn;
}

// A chest starts at 0,0 and moves to a passable random cell on init.

${dungeons.map((r) => chest(r.map, +r.tier)).join('\n')}`;
}

function main() {
  const rows = atlas.parse(fs.readFileSync(CSV, 'utf8'));
  const errors = atlas.validate(rows);
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  const out = render(rows);
  const count = rows.filter((r) => r.kind === 'dungeon').length;
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('dungeon-chests.txt is out of date; run build_chests.cjs');
      process.exit(1);
    }
    console.log(`up to date (${count} chests)`);
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${count} chests)`);
}

if (require.main === module) main();
module.exports = { render, REWARDS };
