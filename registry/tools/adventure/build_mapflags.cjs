#!/usr/bin/env node
// Turns every row of world-atlas's atlas.csv into a `loadevent` mapflag in
// my-mods/adventure/npc/adventure-maps.txt. adventure notices a map change with
// OnPCLoadMapEvent, which rAthena only fires on maps with that flag, so a map
// in the atlas is a map adventure sees: adding a row to atlas.csv and running
// this script is how a map starts giving experiences.
//
//   node build_mapflags.cjs           write the file
//   node build_mapflags.cjs --check   fail if the file on disk is out of date
//
// Cities and interiors get the flag too: entering one closes the time spent
// outside. The mod ships the generated file, never this script.

const fs = require('fs');
const path = require('path');
const atlas = require('../world-atlas/build_atlas.cjs');

const CSV = path.join(__dirname, '..', 'world-atlas', 'atlas.csv');
const OUT = path.join(__dirname, '..', '..', '..', 'my-mods', 'adventure', 'npc', 'adventure-maps.txt');

function render(rows) {
  const maps = rows.map((r) => r.map)
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return `// GENERATED by registry/tools/adventure/build_mapflags.cjs from
// registry/tools/world-atlas/atlas.csv. Edit the CSV and rebuild; changes here
// are lost.
//
// ${maps.length} maps. OnPCLoadMapEvent only runs on maps with loadevent.

${maps.map((m) => `${m}\tmapflag\tloadevent`).join('\n')}
`;
}

function main() {
  const rows = atlas.parse(fs.readFileSync(CSV, 'utf8'));
  const errors = atlas.validate(rows);
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  const out = render(rows);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('adventure-maps.txt is out of date; run build_mapflags.cjs');
      process.exit(1);
    }
    console.log(`up to date (${rows.length} maps)`);
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${rows.length} maps)`);
}

if (require.main === module) main();
module.exports = { render };
