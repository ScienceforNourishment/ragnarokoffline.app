#!/usr/bin/env node
// Turns rAthena's Renewal element table (db/re/attr_fix.yml) into
// my-mods/tavern-rumors/npc/tavern-elements.txt: for each defending element and
// level, which attacking elements hurt most and which do nothing or little.
//
//   node build_elements.cjs [attr_fix.yml]           write the script
//   node build_elements.cjs [attr_fix.yml] --check   fail if it is out of date
//
// The table defaults to vendor/rathena/db/re/attr_fix.yml; pass another path
// when there is no vendor checkout. Rebuild when the rAthena pin moves.
// The mod ships the generated script, never this file.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..', '..');
const DEFAULT_IN = path.join(ROOT, 'vendor', 'rathena', 'db', 're', 'attr_fix.yml');
const OUT = path.join(ROOT, 'my-mods', 'tavern-rumors', 'npc', 'tavern-elements.txt');

// rAthena's Ele_* order, which getmonsterinfo(MOB_ELEMENT) returns.
const ELEMENTS = ['Neutral', 'Water', 'Earth', 'Fire', 'Wind', 'Poison', 'Holy', 'Dark', 'Ghost', 'Undead'];
// An attack at this rate or below "barely scratches" the target.
const LOW = 50;

// attr_fix.yml: Level -> attacking element -> defending element: rate.
function parse(text) {
  const rate = {};
  let level = 0;
  let attack = '';
  for (const line of text.split(/\r?\n/)) {
    let m;
    if ((m = line.match(/^  - Level: (\d+)/))) level = +m[1];
    else if ((m = line.match(/^    (\w+):\s*$/))) attack = m[1];
    else if ((m = line.match(/^      (\w+): (-?\d+)/))) {
      const def = m[1];
      ((rate[level] ??= {})[def] ??= {})[attack] = +m[2];
    }
  }
  for (let lv = 1; lv <= 4; lv++) {
    for (const d of ELEMENTS) {
      for (const a of ELEMENTS) {
        if (typeof rate[lv]?.[d]?.[a] !== 'number') throw new Error(`attr_fix.yml: no rate for ${a} against ${d} level ${lv}`);
      }
    }
  }
  return rate;
}

function render(rate) {
  const idx = (names) => names.map((n) => ELEMENTS.indexOf(n)).join('|');
  const lines = [];
  for (let d = 0; d < ELEMENTS.length; d++) {
    for (let lv = 1; lv <= 4; lv++) {
      const r = rate[lv][ELEMENTS[d]];
      const top = Math.max(...ELEMENTS.map((a) => r[a]));
      const best = top > 100 ? ELEMENTS.filter((a) => r[a] === top) : [];
      const none = ELEMENTS.filter((a) => r[a] <= 0);
      const low = ELEMENTS.filter((a) => r[a] > 0 && r[a] <= LOW);
      const k = d * 10 + lv;
      lines.push(`\t.best$[${k}] = "${idx(best)}";\t.none$[${k}] = "${idx(none)}";\t.low$[${k}] = "${idx(low)}";\t// ${ELEMENTS[d]} ${lv}`);
    }
  }
  return `// GENERATED by registry/tools/tavern-rumors/build_elements.cjs from rAthena's
// db/re/attr_fix.yml. Rebuild when the rAthena pin moves; changes here are lost.
//
// Indexed by element * 10 + element level (Ele_* order, as getmonsterinfo
// MOB_ELEMENT and MOB_ELEMENTLV return them). Each value is a list of attacking
// elements joined with "|": .best$ those that hurt most (empty when none beats
// 100 %), .none$ those that do nothing, .low$ those that do ${LOW} % or less.

-	script	tavern_data	-1,{
OnInit:
${lines.join('\n')}
	end;
}
`;
}

function main() {
  const args = process.argv.slice(2);
  const input = args.find((a) => !a.startsWith('--')) || DEFAULT_IN;
  if (!fs.existsSync(input)) {
    console.error(`no ${input}; pass the path to rAthena's db/re/attr_fix.yml`);
    process.exit(1);
  }
  const out = render(parse(fs.readFileSync(input, 'utf8')));
  if (args.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('tavern-elements.txt is out of date; run build_elements.cjs');
      process.exit(1);
    }
    console.log('up to date (40 element levels)');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (40 element levels)`);
}

if (require.main === module) main();
module.exports = { parse, render };
