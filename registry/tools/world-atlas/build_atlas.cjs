#!/usr/bin/env node
// Turns atlas.csv into my-mods/world-atlas/npc/world-atlas.txt.
//
//   node build_atlas.cjs           write the script
//   node build_atlas.cjs --check   fail if the script on disk is out of date
//
// The mod ships the generated script, never this file or the CSV.

const fs = require('fs');
const path = require('path');

const CSV = path.join(__dirname, 'atlas.csv');
const OUT = path.join(__dirname, '..', '..', '..', 'my-mods', 'world-atlas', 'npc', 'world-atlas.txt');

const KINDS = ['city', 'field', 'dungeon', 'interior'];
const BIOMES = ['ciudad', 'pradera', 'bosque', 'selva', 'desierto', 'nieve', 'pantano',
  'costa', 'montana', 'volcan', 'cueva', 'ruinas'];
const COLUMNS = ['map', 'kind', 'biome', 'tier', 'temp', 'anchor', 'water', 'rest', 'name', 'note'];

function parse(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim() !== '');
  if (lines[0].trim() !== COLUMNS.join(',')) {
    throw new Error(`atlas.csv header must be: ${COLUMNS.join(',')}`);
  }
  return lines.slice(1).map((line, i) => {
    const f = line.split(',');
    if (f.length !== COLUMNS.length) throw new Error(`line ${i + 2}: expected ${COLUMNS.length} columns, got ${f.length}`);
    const r = Object.fromEntries(COLUMNS.map((c, k) => [c, f[k].trim()]));
    r.line = i + 2;
    return r;
  });
}

function validate(rows) {
  const errors = [];
  const seen = new Set();
  const cities = new Set(rows.filter((r) => r.kind === 'city').map((r) => r.map));
  for (const r of rows) {
    const at = `line ${r.line} (${r.map})`;
    if (!/^[a-z0-9_]+$/.test(r.map)) errors.push(`${at}: map must be lowercase letters, digits and _ only`);
    if (seen.has(r.map)) errors.push(`${at}: duplicate map`);
    seen.add(r.map);
    if (!KINDS.includes(r.kind)) errors.push(`${at}: kind '${r.kind}' not in ${KINDS.join('|')}`);
    if (!BIOMES.includes(r.biome)) errors.push(`${at}: biome '${r.biome}' not in the list`);
    if (!/^\d+$/.test(r.tier) || +r.tier > 6) errors.push(`${at}: tier must be 0-6`);
    if (r.kind === 'city' && r.tier !== '0') errors.push(`${at}: a city has tier 0`);
    if (r.kind !== 'city' && r.tier === '0') errors.push(`${at}: only a city has tier 0`);
    if (!/^-?\d+$/.test(r.temp) || Math.abs(+r.temp) > 2) errors.push(`${at}: temp must be -2..2`);
    if (!cities.has(r.anchor)) errors.push(`${at}: anchor '${r.anchor}' is not a city row`);
    for (const c of ['water', 'rest']) if (!/^[01]$/.test(r[c])) errors.push(`${at}: ${c} must be 0 or 1`);
    if (r.name === '') errors.push(`${at}: name is required`);
    for (const c of ['name', 'note']) {
      if (r[c].includes('|') || r[c].includes('"')) errors.push(`${at}: ${c} cannot contain | or "`);
    }
  }
  return errors;
}

function render(rows) {
  const T = '\t';
  const records = rows
    .map((r) => `\t$@wa_${r.map}$ = "${[r.kind, r.biome, r.tier, r.temp, r.anchor, r.water, r.rest, r.name].join('|')}";`)
    .join('\n');
  const count = rows.length;

  return `// GENERATED by registry/tools/world-atlas/build_atlas.cjs from atlas.csv.
// Edit the CSV and rebuild; changes here are lost.
//
// ${count} maps. Each record is one temporary server variable, $@wa_<map>$:
//   kind|biome|tier|temp|anchor|water|rest|name
// Unknown maps get a default, never an error. Query at run time, not from
// another NPC's OnInit: this NPC fills the table in its own OnInit and the
// load order between NPCs is not guaranteed.

-${T}script${T}WorldAtlas${T}-1,{
OnInit:
${records}
\t$@wa_ready = 1;
\tend;
}

// Every accessor takes the map name; with no argument it uses the current map of
// the attached character. The default is resolved with an if/else, not with
// getarg(0, strcharinfo(3)): script arguments are all evaluated, so that form
// would call strcharinfo even when a map is given, and logs an error when there
// is no attached character (a timer, an OnInit).

// F_Atlas_Record(map$) -> the raw record, or "" when the atlas has no such map.
function${T}script${T}F_Atlas_Record${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	.@m$ = strtolower(.@m$);
	// Instance maps are named like 1@tower; they are not valid variable names.
	if (.@m$ == "" || compare(.@m$, "@"))
		return "";
	return getd("$@wa_" + .@m$ + "$");
}

// F_Atlas_Field(map$, index) -> one field of the record, "" when unknown.
// Both arguments are required. index: 0 kind, 1 biome, 2 tier, 3 temp, 4 anchor,
// 5 water, 6 rest, 7 name
function${T}script${T}F_Atlas_Field${T}{
	.@r$ = callfunc("F_Atlas_Record", getarg(0));
	if (.@r$ == "")
		return "";
	explode(.@f$, .@r$, "|");
	return .@f$[getarg(1)];
}

// F_Atlas_Has(map$) -> 1 when the atlas knows the map.
function${T}script${T}F_Atlas_Has${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return (callfunc("F_Atlas_Record", .@m$) != "");
}

// "city", "field", "dungeon" or "interior"; "" when unknown.
function${T}script${T}F_Atlas_Kind${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return callfunc("F_Atlas_Field", .@m$, 0);
}

// Biome name (see the CSV); "" when unknown.
function${T}script${T}F_Atlas_Biome${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return callfunc("F_Atlas_Field", .@m$, 1);
}

// Danger tier: 0 for a city, 1-6 elsewhere; 0 when unknown.
function${T}script${T}F_Atlas_Tier${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return atoi(callfunc("F_Atlas_Field", .@m$, 2));
}

// Base temperature, -2 (cold) to 2 (hot), 0 comfortable; 0 when unknown.
function${T}script${T}F_Atlas_Temp${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return atoi(callfunc("F_Atlas_Field", .@m$, 3));
}

// Anchor city map name; "" when unknown.
function${T}script${T}F_Atlas_Anchor${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return callfunc("F_Atlas_Field", .@m$, 4);
}

// 1 when there is water to fill a bottle; 0 when not or unknown.
function${T}script${T}F_Atlas_Water${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return atoi(callfunc("F_Atlas_Field", .@m$, 5));
}

// 1 when the map has a shelter or camp; 0 when not or unknown.
function${T}script${T}F_Atlas_Rest${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return atoi(callfunc("F_Atlas_Field", .@m$, 6));
}

// Readable place name, e.g. "Campo de Prontera 08"; "" when unknown, so the
// caller falls back to the map code.
function${T}script${T}F_Atlas_Name${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return callfunc("F_Atlas_Field", .@m$, 7);
}

// 1 on a city map. Unknown maps are not safe.
function${T}script${T}F_Atlas_IsSafe${T}{
	if (getargcount() > 0)
		.@m$ = getarg(0);
	else
		.@m$ = strcharinfo(3);
	return (callfunc("F_Atlas_Kind", .@m$) == "city");
}
`;
}

function main() {
  const rows = parse(fs.readFileSync(CSV, 'utf8'));
  const errors = validate(rows);
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  const out = render(rows);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('world-atlas.txt is out of date; run build_atlas.cjs');
      process.exit(1);
    }
    console.log(`up to date (${rows.length} maps)`);
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${rows.length} maps)`);
}

if (require.main === module) main();
module.exports = { parse, validate, render };
